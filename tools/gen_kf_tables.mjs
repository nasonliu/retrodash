// VaveHero's sound tables for the firmware, from the reference (reference/vavehero.html is the fasit): the patches
// (SYNTH, FMP, PATCHSET), the drum kits (KITS, DRUMKIT, TOMF), and the curves and lookup tables the engine uses.
// The laws (envelope times, filter Q in dB, detune in cents) are worked out here in floating point, once, so the
// firmware only does integers (docs/RULES.md).
//   node tools/gen_kf_tables.mjs            -> firmware/gen/kf_tables.h
//   node tools/gen_kf_tables.mjs --check    exit 1 if the header is not what this would write
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const html = readFileSync(join(ROOT, 'reference/vavehero.html'), 'utf8');
function grab(name) {                                   // `const NAME = {...};` (or [...]) as the reference has it
  const at = html.indexOf(`const ${name} = `);
  if (at < 0) throw new Error(`reference: no const ${name}`);
  let i = html.indexOf('=', at) + 1, depth = 0, start = -1;
  for (; i < html.length; i++) {
    const c = html[i];
    if (c === '{' || c === '[') { if (depth++ === 0) start = i; }
    else if (c === '}' || c === ']') { if (--depth === 0) break; }
  }
  return new Function(`return (${html.slice(start, i + 1)});`)();
}
const SYNTH = grab('SYNTH'), FMP = grab('FMP'), PATCHSET = grab('PATCHSET'), KITS = grab('KITS');
const DRUMKIT = grab('DRUMKIT'), TOMF = grab('TOMF');

const FS = 44100, TICK = 32, T = TICK / FS;              // the control rate: every 32 frames
const q = (x, bits) => Math.round(x * 2 ** bits);
const clampi = (x, lo, hi) => Math.max(lo, Math.min(hi, x));
const incOf = f => Math.round(f * 2 ** 32 / FS) >>> 0;    // a phase step per frame
const coefTo = tau => q(1 - Math.exp(-T / tau), 24);    // setTargetAtTime: v += (target - v) * c, a tick
const mulOf = tau => q(Math.exp(-T / tau), 24);         // v *= m, a tick
const qlinDb = qdb => 10 ** (qdb / 20);                 // a WebAudio low-pass / high-pass Q is in dB
const WAVE = { sawtooth: 0, square: 1, triangle: 2, sine: 3 };
/* Chromium normalises its built-in saw and square to a peak of 1, the Gibbs overshoot included: 1 / 1.17898 */
const GIBBS = 1 / 1.17898;
const BUS = { player: 0, band: 1, chorus: 2 };
const PARTS = ['PLAY', 'BASS', 'PAD', 'ARP', 'LEAD', 'KEYS'];
const DRIVES = [...new Set([...Object.values(SYNTH), ...Object.values(FMP), ...Object.values(KITS)]
  .filter(p => p.drive).map(p => p.drive))].sort((a, b) => a - b);
if (Object.values(KITS).some(k => k.crush && !k.drive)) DRIVES.unshift(1);

/* FM voices with whole-number ratios: their level depends on the modulators' phase against the carrier (up to 4 dB
 * for ORGAN). In the reference that phase follows the note's sub-sample start time, so its level spreads from note
 * to note; the firmware starts each modulator at the phase that gives the reference's average (a uniform phase's
 * mean power), found here by simulating the firmware's own FM loop. */
function fmPhases(p, pitch) {
  const f = 440 * 2 ** ((pitch - 69) / 12), n = Math.round(.35 * FS), N = 12, mods = p.mods;
  const pw = (ph) => {
    let cph = 0, sum = 0; const mph = mods.map((m, k) => ph[k]), idx = mods.map(m => m[1]);
    const a = mods.map(m => m[1] * m[2]), dc = mods.map(m => 1 - Math.exp(-1 / (m[3] * FS)));
    for (let i = 0; i < n; i++) {
      const tt = i / FS, env = tt < p.att ? tt / p.att : p.sus + (1 - p.sus) * Math.exp(-(tt - p.att) / p.dec);
      let s = Math.sin(cph);
      if (p.drive) s = Math.tanh(p.drive * s) / Math.tanh(p.drive);
      sum += (s * env) ** 2;
      let inc = 2 * Math.PI * f / FS;
      mods.forEach((m, k) => { inc += idx[k] * 2 * Math.PI * f * m[0] / FS * Math.sin(mph[k]); mph[k] += 2 * Math.PI * f * m[0] / FS; idx[k] += (a[k] - idx[k]) * dc[k]; });
      cph += inc;
    }
    return sum / n;
  };
  const grid = [];
  for (let i = 0; i < N; i++) for (let j = 0; j < (mods.length > 1 ? N : 1); j++) {
    const ph = [2 * Math.PI * i / N, 2 * Math.PI * j / N];
    grid.push({ ph, p: pw(ph) });
  }
  const mean = grid.reduce((s, g) => s + g.p, 0) / grid.length;
  grid.sort((x, y) => Math.abs(x.p - mean) - Math.abs(y.p - mean));
  return grid[0].ph.map(x => Math.round(x / (2 * Math.PI) * 2 ** 32) >>> 0);
}

const out = [];
const w = s => out.push(s);
w('/* SPDX-License-Identifier: GPL-3.0-only */');
w('/* Generated by tools/gen_kf_tables.mjs from reference/vavehero.html: do not edit, run the tool. */');
w('#pragma once');
w('#include <stdint.h>');
w('');
w(`#define KF_TICK ${TICK}u                         /* frames a control tick */`);

/* ---- the patches */
const ids = [];                                          // the engine's patch ids: the parts' patches in PATCHSET order
for (const part of PARTS) for (const name of PATCHSET[part]) ids.push({ part, name });
w(`#define KF_NPATCH ${ids.length}u`);
w(`#define KF_NDRIVE ${DRIVES.length}u`);
PARTS.forEach((p, i) => w(`#define KF_P_${p} ${i}u`));
w('#define KF_P_DRUMS 6u');
w('#define KF_NPART 7u');
w('');
w('typedef struct {');
w('    uint8_t fm, bus, nosc, swell;               /* fm: 1 = an FM voice; bus: 0 player, 1 band, 2 chorus */');
w('    uint8_t wav[4];                             /* 0 saw, 1 square, 2 triangle */');
w('    int16_t lvl[4];                             /* Q12 (saw and square: times 0.848, as Chromium normalises them) */');
w('    uint32_t ratio[4];                          /* Q16: the detune, 2^(cents / 1200) */');
w('    int32_t cut, env;                           /* Hz: the filter at rest, and how far its envelope opens it */');
w('    int32_t k;                                  /* Q15: 1 / Q (Q from dB, as WebAudio\'s low-pass) */');
w('    int32_t m_envt;                             /* Q24: the filter envelope\'s fall a tick */');
w('    int32_t att, ramp;                          /* frames: the attack; the swell\'s filter ramp */');
w('    int32_t c_dec, c_rel;                       /* Q24: the decay\'s and the release\'s step a tick */');
w('    int32_t sus;                                /* Q15 */');
w('    int32_t amp;                                /* Q24 */');
w('    int32_t rel_end;                            /* ticks after the release: the voice is free */');
w('    int16_t rev, dly;                           /* Q15: the sends */');
w('    int32_t vib;                                /* cents Q8 at full depth (0: none) */');
w('    int8_t drive;                               /* the drive curve, -1: none */');
w('    int16_t crush;                              /* Q15: the crushed copy\'s level */');
w('    uint8_t nmod;                               /* FM: the modulators */');
w('    uint32_t mratio[2];                         /* Q16 */');
w('    int32_t midx[2];                            /* the index, Q12: the deviation is index x the modulator\'s frequency */');
w('    int32_t msus[2];                            /* Q15 */');
w('    int32_t c_mdec[2];                          /* Q24 */');
w('    uint32_t mph0[2];                           /* the modulators\' phase at the start (whole-number ratios: the average level) */');
w('    const char *name;');
w('} kf_patch_t;');
w('');
w('static const kf_patch_t KF_PATCH[KF_NPATCH] = {');
for (const { part, name } of ids) {
  const fm = !SYNTH[name], p = fm ? FMP[name] : SYNTH[name];
  if (!p) throw new Error(`no patch ${name}`);
  const f = [];
  f.push(`${fm ? 1 : 0}, ${BUS[p.bus]}, ${fm ? 0 : p.osc.length}, ${p.swell ? 1 : 0}`);
  const osc = fm ? [] : p.osc;
  if (osc.length > 4) throw new Error(`${name}: more than 4 oscillators`);
  const pad = (a, v) => { const r = a.slice(); while (r.length < 4) r.push(v); return r; };
  f.push(`{${pad(osc.map(o => WAVE[o[0]]), 0).join(', ')}}`);
  f.push(`{${pad(osc.map(o => q(o[2] * (o[0] === 'triangle' ? 1 : GIBBS), 12)), 0).join(', ')}}`);
  f.push(`{${pad(osc.map(o => q(2 ** (o[1] / 1200), 16) + 'u'), '0u').join(', ')}}`);
  f.push(`${fm ? 0 : p.cut}, ${fm ? 0 : p.env}`);
  f.push(`${fm ? 0 : q(1 / qlinDb(p.q), 15)}`);
  f.push(`${fm ? 0 : mulOf(p.envT)}`);
  f.push(`${Math.max(1, Math.round(p.att * FS))}, ${Math.round(Math.max(.01, p.att) * FS)}`);
  f.push(`${coefTo(p.dec)}, ${coefTo(p.rel)}`);
  f.push(`${q(p.sus, 15)}`);
  f.push(`${q(p.amp, 24)}`);
  f.push(`${Math.ceil(p.rel * 6 / T)}`);
  f.push(`${q(p.rev || 0, 15)}, ${q(p.dly || 0, 15)}`);
  f.push(`${q(p.vib || 0, 8)}`);
  f.push(`${p.drive ? DRIVES.indexOf(p.drive) : -1}`);
  f.push(`${q(p.crush || 0, 15)}`);
  const mods = fm ? p.mods : [];
  if (mods.length > 2) throw new Error(`${name}: more than 2 modulators`);
  const pm = (a, v) => { const r = a.slice(); while (r.length < 2) r.push(v); return r; };
  f.push(`${mods.length}`);
  f.push(`{${pm(mods.map(m => q(m[0], 16) + 'u'), '0u').join(', ')}}`);
  f.push(`{${pm(mods.map(m => q(m[1], 12)), 0).join(', ')}}`);
  f.push(`{${pm(mods.map(m => q(m[2], 15)), 0).join(', ')}}`);
  f.push(`{${pm(mods.map(m => coefTo(m[3])), 0).join(', ')}}`);
  f.push(`{${(fm && mods.some(m => Number.isInteger(m[0]) || Math.abs(m[0] - Math.round(m[0])) < .01) ? fmPhases(p, part === 'BASS' ? 36 : 60) : [0, 0]).map(x => x + 'u').join(', ')}}`);
  f.push(`"${name}"`);
  w(`    {${f.join(', ')}},   /* ${part} */`);
}
w('};');
w('');
const first = {}; ids.forEach((d, i) => { if (first[d.part] == null) first[d.part] = i; });
w(`static const uint8_t KF_PART_FIRST[KF_NPART] = {${PARTS.map(p => first[p]).join(', ')}, 0};   /* a part's first patch */`);
w(`static const uint8_t KF_PART_COUNT[KF_NPART] = {${PARTS.map(p => PATCHSET[p].length).join(', ')}, ${PATCHSET.DRUMS.length}};`);
w('');

/* ---- the drive curves: tanh(a x) / tanh(a), x in -1..1, 257 points */
w(`/* drive: tanh(a x) / tanh(a) for a = ${DRIVES.join(', ')}; 257 points over -1..1, Q15 */`);
w('static const int16_t KF_DRIVE[KF_NDRIVE][257] = {');
for (const a of DRIVES) {
  const r = [];
  for (let i = 0; i <= 256; i++) { const x = i / 128 - 1; r.push(clampi(q(Math.tanh(a * x) / Math.tanh(a), 15), -32767, 32767)); }
  w(`    {${r.join(',')}},`);
}
w('};');
w('');

/* ---- the filter: g = tan(pi f / fs) for the TPT state-variable filter, f = 0..22016 Hz in 32 Hz steps, Q15 */
const NG = 689;
const g = [];
for (let i = 0; i < NG; i++) g.push(q(Math.tan(Math.PI * Math.min(i * 32, 21800) / FS), 15));
w(`/* the filter's g = tan(pi f / 44100), f = 32 i Hz (to 21800), Q15 */`);
w(`#define KF_NG ${NG}u`);
w(`static const int32_t KF_G[KF_NG] = {${g.join(',')}};`);
w('');

/* ---- the sine, 4096 points, Q15 */
const sn = [];
for (let i = 0; i < 4096; i++) sn.push(clampi(q(Math.sin(2 * Math.PI * i / 4096), 15), -32767, 32767));
w('static const int16_t KF_SINE[4096] = {' + sn.join(',') + '};');
w('');

/* ---- MIDI note -> phase step */
w('static const uint32_t KF_INC[128] = {' + Array.from({ length: 128 }, (_, m) => incOf(440 * 2 ** ((m - 69) / 12)) + 'u').join(',') + '};');
/* velocity -> log2(v / 127), Q16 (the drums' exponential decays start at gain * v) */
w('static const int32_t KF_LOG2VEL[128] = {' + Array.from({ length: 128 }, (_, v) => v ? Math.round(Math.log2(v / 127) * 65536) : -7 * 65536).join(',') + '};');
w('');

/* ---- the drum kits */
const LAYER = { tone: 0, noise: 1 };
const FLT = { lowpass: 0, highpass: 1, bandpass: 2 };
function svf(type, f, Q) {                               // the TPT SVF's coefficients for a fixed filter
  const gg = Math.tan(Math.PI * f / FS), k = 1 / (type === 'bandpass' ? Q : qlinDb(Q)), a1 = 1 / (1 + gg * (gg + k));
  return { k: q(k, 15), a1: q(a1, 15), a2: q(gg * a1, 15), a3: q(gg * gg * a1, 15) };
}
const KINDS = ['kick', 'snare', 'clap', 'rim', 'hat', 'ohat', 'crash', 'tom1', 'tom2', 'tom3', 'tom4', 'tom5'];
const layers = [], kitIndex = [];
const L = (o) => layers.push(o);
for (const kit of PATCHSET.DRUMS) {
  const K = KITS[kit];
  const gate = (amt) => K.gate ? { gate: amt * K.gate, rev: 0 } : { gate: 0, rev: amt * .12 };
  const kinds = [];
  for (const kind of KINDS) {
    const from = layers.length;
    const tone = (wave, f0, f1, sweep, dec, gain, s = {}) => L({ type: 'tone', wave, f0, f1, sweep, dec, gain, at: 0, ...s });
    const noise = (ft, f, Q, dec, gain, at = 0, s = {}) => L({ type: 'noise', ft, f, Q, dec, gain, at, ...s });
    if (kind === 'kick') { tone('sine', ...K.kick); noise('highpass', 3500, .7, .012, .28); }
    else if (kind === 'snare') {
      const a = gate(.6), b = gate(1.1);
      tone('triangle', 210, 160, .06, K.sn * .6, .38, a);
      noise('bandpass', 1900, .7, K.sn, .46, 0, { gate: b.gate, rev: b.rev + .1 });
    } else if (kind === 'clap') {
      for (let k = 0; k < 3; k++) noise('bandpass', 1250, 1.2, .03, .45, k * .011, gate(.7));
      noise('bandpass', 1250, 1.2, .16, .3, 0, gate(.9));
    }
    else if (kind === 'rim') noise('bandpass', 2400, 2.5, .05, .5);
    else if (kind === 'hat') noise('highpass', 8200, .7, .04, .2);
    else if (kind === 'ohat') noise('highpass', 7600, .7, .26, .14, 0, { rev: .1 });
    else if (kind === 'crash') noise('highpass', 5200, .5, 1.7, .2, 0, { rev: .3 });
    else { const f = TOMF[kind]; tone('sine', f * 1.7, f, .22, K.tom, .7, { rev: .35 }); }
    kinds.push([from, layers.length - from]);
  }
  kitIndex.push({ kit, K, kinds });
}
w('typedef struct {');
w('    uint8_t noise, wav, flt;                    /* noise: 1 = filtered noise, else a tone (wav: 2 triangle, 3 sine); flt: 1 HP, 2 BP */');
w('    uint32_t inc;                               /* tone: the phase step at the start */');
w('    int32_t m_sweep, sweep;                     /* tone: Q24 the pitch\'s fall a tick, for so many ticks */');
w('    int32_t k, a1, a2, a3;                      /* noise: the filter, Q15 */');
w('    int32_t tdec;                               /* Q24: a tick / the decay (the exponential ramp to 0.001) */');
w('    int32_t end;                                /* ticks: the layer stops (decay + 50 ms) */');
w('    int32_t gain, lgain;                        /* Q15, and log2(gain) Q16 */');
w('    int32_t at;                                 /* ticks after the hit */');
w('    int32_t gate, rev;                          /* Q15: the sends (the snare\'s gate send is 1.1) */');
w('} kf_layer_t;');
w(`#define KF_NLAYERDEF ${layers.length}u`);
w('static const kf_layer_t KF_LAYER[KF_NLAYERDEF] = {');
for (const l of layers) {
  let fl = { k: 0, a1: 0, a2: 0, a3: 0 };
  if (l.type === 'noise') fl = svf(l.ft, l.f, l.Q);
  const m_sweep = l.type === 'tone' ? q(Math.pow(l.f1 / l.f0, T / l.sweep), 24) : 0;
  w(`    {${l.type === 'noise' ? 1 : 0}, ${l.type === 'tone' ? WAVE[l.wave] : 0}, ${l.type === 'noise' ? FLT[l.ft] : 0}, ` +
    `${l.type === 'tone' ? incOf(l.f0) : 0}u, ${m_sweep}, ${l.type === 'tone' ? Math.round(l.sweep / T) : 0}, ` +
    `${fl.k}, ${fl.a1}, ${fl.a2}, ${fl.a3}, ${q(T / l.dec, 24)}, ${Math.ceil((l.dec + .05) / T)}, ` +
    `${q(l.gain, 15)}, ${Math.round(Math.log2(l.gain) * 65536)}, ${Math.round(l.at / T)}, ${q(l.gate || 0, 15)}, ${q(l.rev || 0, 15)}},`);
}
w('};');
w('typedef struct {');
w('    uint8_t first[12], n[12];                   /* kick snare clap rim hat ohat crash tom1..tom5: their layers */');
w('    int8_t drive;                               /* the kit\'s drive curve, -1: clean */');
w('    int16_t crush, level;                       /* Q15 */');
w('    const char *name;');
w('} kf_kit_t;');
w(`#define KF_NKIT ${kitIndex.length}u`);
w('static const kf_kit_t KF_KIT[KF_NKIT] = {');
for (const { kit, K, kinds } of kitIndex) {
  const dr = K.drive || K.crush ? DRIVES.indexOf(K.drive || 1) : -1;
  w(`    {{${kinds.map(k => k[0]).join(', ')}}, {${kinds.map(k => k[1]).join(', ')}}, ${dr}, ${q(K.crush || 0, 15)}, ${q(K.level || 1, 15) > 32767 ? 32767 : q(K.level || 1, 15)}, "${kit}"},`);
}
w('};');
/* General MIDI drum note -> kind */
const gm = new Array(128).fill(255);
for (const [n, kind] of Object.entries(DRUMKIT)) gm[+n] = KINDS.indexOf(kind);
w('static const uint8_t KF_GM[128] = {' + gm.join(',') + '};   /* GM drum note -> kind, 255: none */');
w('');

const text = out.join('\n') + '\n';
const dst = join(ROOT, 'firmware/gen/kf_tables.h');
if (process.argv.includes('--check')) {
  let cur = ''; try { cur = readFileSync(dst, 'utf8'); } catch {}
  if (cur !== text) { console.error('firmware/gen/kf_tables.h is out of date: node tools/gen_kf_tables.mjs'); process.exit(1); }
  console.log('kf_tables.h up to date');
} else {
  writeFileSync(dst, text);
  console.log(`firmware/gen/kf_tables.h: ${ids.length} patches, ${kitIndex.length} kits (${layers.length} layers), drives ${DRIVES.join(' ')}`);
}
