#!/usr/bin/env python3
"""Embed a selected SPC project's audio, chart and artwork for the FM-1."""
import argparse, json, struct, math, hashlib
from pathlib import Path
import lz4blk
from cq_bundle import build
ROOT=Path(__file__).resolve().parents[1]
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('project',type=Path,nargs='?',default=ROOT/'projects/peaceful-days-spc')
p=parser.parse_args().project.resolve()
chart=json.loads((p/'chart/chart.json').read_text())
notes=json.loads((p/'audio/voices.json').read_text())
def array(name,data):
 return f'static const unsigned char {name}[] __attribute__((aligned(4))) = {{\n'+',\n'.join(','.join(map(str,data[i:i+32])) for i in range(0,len(data),32))+'\n};\n'
ram=(p/'audio/aram.bin').read_bytes();packed=lz4blk.compress(ram)
assert lz4blk.decompress(packed)==ram
text='/* Generated by gen_spc_firmware.py from the user-supplied SPC. */\n#pragma once\n'
text+=array('RD_SPC_RAM',packed)+array('RD_SPC_REGS',(p/'audio/dsp-registers.bin').read_bytes())+array('RD_SPC_EVENTS',(p/'audio/events.sde').read_bytes())
text+='struct rd_spc_target { unsigned clock, duration; unsigned char regs[8]; };\nstatic const rd_spc_target RD_SPC_TARGETS[] = {\n'
for t in chart['targets']:
 n=notes[t['noteIndex']];regs=n['volumeLR']+[n['pitch']&255,n['pitch']>>8,n['srcn']]+n['adsr']+[n['gain']]
 text+='{%du,%du,{%s}},\n'%(n['clock'],max(32,n['gateEndClock']-n['clock']),','.join(map(str,regs)))
text+='};\n'
(ROOT/'firmware/gen/rd_spc_data.h').write_text(text)
# Compile this song project's own artwork and SPC-derived chart directly.
bpm=round(chart.get('bpm',87.27)*100)
fpt=round(44100*60/(bpm/100*96)*65536)
tm=lambda c:round(c*96*bpm/(6000*1024000))
C=[(tm(t['clock']),max(1,tm(t['gateEndClock'])-tm(t['clock'])),t['keyMidiPitch'],t['keyIndex'],2,0) for t in chart['targets']]
new_chart=b''.join(struct.pack('<HHBBbB',*row) for row in C)
hash_=int.from_bytes(hashlib.sha256(new_chart).digest()[:2],'little')&0x3fff
manifest=json.loads((p/'manifest.json').read_text())
song=(C,[],math.ceil(manifest['durationSeconds']*bpm/6000),bpm,fpt,hash_,{t['keyMidiPitch']:t['keyIndex'] for t in chart['targets']})
data,report=build(p,song)
out=ROOT/'build/spc-device';out.mkdir(parents=True,exist_ok=True)
(out/'peaceful-days-spc.cqp').write_bytes(data)
(out/'project.report.json').write_text(json.dumps(report,indent=2)+'\n')
(ROOT/'firmware/gen/cq_spc_demo.h').write_text('#pragma once\n'+array('CQ_DEMO_DATA',data))
types=(ROOT/'firmware/gen/kf_songs.h').read_text().split('static const kf_cnote_t KF_S0_C')[0]
(ROOT/'firmware/gen/kf_spc_song.h').write_text(types+'\n#define KF_NSONG 1u\nstatic kf_song_t KF_SONG[1];\n')
print('SPC ARAM compressed',len(packed),'events',(p/'audio/events.sde').stat().st_size,'targets',len(chart['targets']))
